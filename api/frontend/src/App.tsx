/**
 * ============================================================================
 * ASCEND - Document Conversion Application
 * ============================================================================
 * 
 * This React component manages the complete user interface for converting
 * documents between different formats (AsciiDoc, Markdown, HTML, PDF, etc.).
 * 
 * MAIN ARCHITECTURE:
 * ------------------
 * 1. Conversion utility functions (imported from ./converters)
 *    - convertAsciiDocToMarkdown: AsciiDoc → Markdown conversion via downdoc
 *    - convertMarkdownToAsciiDoc: Markdown → AsciiDoc conversion via Pandoc
 *    - requestConfirmationToken: Secure confirmation token request
 *    - convertText: Generic multi-format conversion function
 * 
 * 2. App Component
 *    - Manages all application states
 *    - Handlers for user interactions
 *    - Conditional rendering based on formats and modes
 * 
 * CONVERSION FLOW:
 * ----------------
 * 1. User enters text in the source panel
 * 2. Select source and destination formats
 * 3. For sensitive conversions: request confirmation token
 * 4. Display confirmation modal
 * 5. Send request with token to backend
 * 6. Display result in destination panel
 * 
 * SECURITY:
 * ---------
 * - Sensitive conversions require a confirmation token
 * - Token is generated by backend and validated before conversion
 * - 30 second timeout on all requests
 * - Network and timeout error handling
 * 
 * NAVIGATION:
 * -----------
 * - Automatic extraction of headings from source panel
 * - Floating navigation window with drag & drop and resizing
 * - Direct navigation to document sections
 * 
 * EDIT MODES:
 * -----------
 * - Result editing mode with save/cancel
 * - Confirmation modals for all destructive actions
 * - Automatic backup of original content before editing
 * 
 * ============================================================================
 */

