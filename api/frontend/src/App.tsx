  const setTargetContent = useCallback((format: FormatType, content: string) => {
    writeResultBuffer(sourceFormat, format, content, {
      setAdocInput,
      setMdOutput,
      setOtherOutput,
    });
  }, [sourceFormat]);

  /**
   * Swaps source and destination formats (swap button/arrows)
   * 
   * LOGIC:
   * 1. Swap sourceFormat ↔ targetFormat
   * 2. Swap content: old result → new source, old source → new result
   * 3. Panels stay in place (source on left, result on right)
   * 
   * USES: getSourceContent, getTargetContent, setSourceContent, setTargetContent
   *       to properly manage content according to formats
   */
  const handleSwap = useCallback(() => {
    if (loading || folderBatchRunning || isEditingResult) return;
    const newSourceFormat = targetFormat;
    const newTargetFormat = sourceFormat;

    const currentSourceText = sourceFormat === 'markdown' ? mdOutput : adocInput;
    const currentTargetText = readResultBuffer(sourceFormat, targetFormat, {
      adocInput,
      mdOutput,
      otherOutput,
    });

    setSourceFormat(newSourceFormat);
    setTargetFormat(newTargetFormat);

    // Place old result into the new source buffer.
    if (newSourceFormat === 'markdown') {
      setMdOutput(currentTargetText);
    } else {
      setAdocInput(currentTargetText);
    }

    // Place old source into the new result buffer (may be otherOutput).
    writeResultBuffer(newSourceFormat, newTargetFormat, currentSourceText, {
      setAdocInput,
      setMdOutput,
      setOtherOutput,
    });
    if (!resultUsesOtherBuffer(newSourceFormat, newTargetFormat)) {
      setOtherOutput('');
    }
    lastAutoConvertKeyRef.current = sourceAutoConvertKey(
      newSourceFormat,
      newTargetFormat,
      currentTargetText
    );
    lastAutoConvertOptionsRef.current = conversionStampRef.current;
    convertSnapshotKeyRef.current = lastAutoConvertKeyRef.current;
    convertSnapshotStampRef.current = conversionStampRef.current;
  }, [sourceFormat, targetFormat, adocInput, mdOutput, otherOutput, loading, folderBatchRunning, isEditingResult]);

