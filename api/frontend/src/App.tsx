  const handleCopy = async () => {
    // Copy result text according to destination format
    const textToCopy = readResultBuffer(sourceFormat, targetFormat, {
      adocInput,
      mdOutput,
      otherOutput,
    });
    if (!textToCopy || !textToCopy.trim()) {
      setStatus("Aucun texte à copier");
      return;
    }
    
    try {
      await navigator.clipboard.writeText(textToCopy);
      setCopied(true);
      setStatus(`Texte copié (${textToCopy.length} caractères)`);
      showSnackbar(`Texte copié (${textToCopy.length} caractères)`);
      setTimeout(() => {
        setCopied(false);
        if (status.includes("copié")) {
          setStatus("");
        }
      }, 2000);
    } catch (err) {
      // Fallback for browsers that do not support Clipboard API
      const textArea = document.createElement("textarea");
      textArea.value = textToCopy;
      textArea.style.position = "fixed";
      textArea.style.left = "-999999px";
      document.body.appendChild(textArea);
      textArea.focus();
      textArea.select();
      try {
        document.execCommand("copy");
        setCopied(true);
        setStatus(`Texte copié (${textToCopy.length} caractères)`);
        showSnackbar(`Texte copié (${textToCopy.length} caractères)`);
        setTimeout(() => {
          setCopied(false);
          if (status.includes("copié")) {
            setStatus("");
          }
        }, 2000);
      } catch (err) {
        setStatus("Erreur lors de la copie");
      }
      document.body.removeChild(textArea);
    }
  };

